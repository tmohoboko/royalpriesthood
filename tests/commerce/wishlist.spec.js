import { test, expect } from '@playwright/test';
const card=page=>page.locator('[data-product-id="RP-W01"]');
test('WI-01/02/03 SMK-02/04/05/06/07 mobile keyboard, persistence, removal and clear',async({page})=>{
 await page.setViewportSize({width:375,height:850});await page.goto('/shop');
 await expect(page.locator('body')).not.toContainText(/enquiry/i);
 await card(page).getByRole('button',{name:'Save to Wishlist'}).click();
 await expect(page.getByRole('button',{name:'Open Wishlist with 1 items'})).toBeVisible();
 await page.goto('/');await page.reload();
 await page.getByRole('button',{name:'Open Wishlist with 1 items'}).click();
 const drawer=page.getByRole('dialog',{name:'My Wishlist'});
 await expect(drawer).toContainText("Women's Black Statement");
 await expect(page.getByRole('button',{name:'Close Wishlist'})).toBeFocused();
 await page.keyboard.press('Shift+Tab');expect(await drawer.evaluate(e=>e.contains(document.activeElement))).toBe(true);
 await page.screenshot({path:'qa/rp-v2.1/ui-acceptance-screenshots/local-mobile-wishlist.png'});
 await page.keyboard.press('Escape');await expect(drawer).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Open Wishlist with 1 items'})).toBeFocused();
 await page.getByRole('button',{name:'Open Wishlist with 1 items'}).click();
 await drawer.getByRole('button',{name:/^Remove /}).click();
 await expect(page.getByRole('button',{name:'Open Wishlist with 0 items'})).toBeVisible();
 await page.keyboard.press('Escape');await page.goto('/shop');
 await card(page).getByRole('button',{name:'Save to Wishlist'}).click();
 await page.getByRole('button',{name:'Open Wishlist with 1 items'}).click();
 await drawer.getByRole('button',{name:'Clear Wishlist',exact:true}).click();
 await expect(drawer).toContainText('Remove all saved items?');
 await drawer.getByRole('button',{name:'Keep items'}).click();await expect(drawer.locator('.drawer-item')).toHaveCount(1);
 await drawer.getByRole('button',{name:'Clear Wishlist',exact:true}).click();await drawer.getByRole('button',{name:'Confirm clear Wishlist'}).click();
 await expect(drawer.locator('.drawer-item')).toHaveCount(0);
});
test('WI-03 SMK-08 move priced variant updates confirmed shared cart',async({page})=>{
 await page.goto('/shop/products/RP-T01');await page.getByLabel('Variant for Black Signature Tee — Front').selectOption('test-black-m');
 await page.getByRole('button',{name:'Save to Wishlist'}).click();
 await page.goto('/shop/cart');
 await expect(page.getByText('Your cart is empty.')).toBeVisible();
 await page.getByRole('button',{name:'Open Wishlist with 1 items'}).click();
 await page.getByRole('button',{name:'Move to Cart'}).click();
 await expect(page.getByRole('link',{name:'Shopping cart with 1 items'})).toBeVisible();
 await expect(page.getByRole('dialog').locator('.drawer-item')).toHaveCount(0);
 await page.keyboard.press('Escape');await page.goto('/shop/cart');
 await expect(page.getByLabel('Quantity for Black Signature Tee — Front')).toHaveValue('1');
});
